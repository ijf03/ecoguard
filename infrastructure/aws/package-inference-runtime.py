"""Run in a bounded AL2023 build task; package and preflight Linux inference dependencies."""
import hashlib
import importlib.metadata
import io
import json
import os
from pathlib import Path
import signal
import subprocess
import sys
import tarfile
import zipfile
import boto3

def deadline(_signum, _frame):
    print('Inference package build deadline exceeded.', flush=True)
    os._exit(124)
signal.signal(signal.SIGALRM, deadline); signal.alarm(840)
s3 = boto3.client('s3')
if boto3.client('sts').get_caller_identity()['Account'] != '851725503164': raise RuntimeError('Wrong build account')
artifacts = os.environ['ECOGUARD_ARTIFACT_BUCKET']
media = os.environ['ECOGUARD_MODEL_BUCKET']
build_id = os.environ['ECOGUARD_BUILD_ID']
source_manifest = json.loads(s3.get_object(Bucket=artifacts, Key=os.environ['ECOGUARD_SOURCE_MANIFEST'])['Body'].read())
if source_manifest.get('complete') is not True: raise RuntimeError('Native/model asset build is incomplete')
target = Path('/tmp/ecoguard-inference'); target.mkdir()
requirements = Path('/tmp/inference-requirements.txt')
requirements.write_bytes(s3.get_object(Bucket=artifacts, Key=os.environ['ECOGUARD_REQUIREMENTS_KEY'])['Body'].read())
subprocess.run([sys.executable, '-m', 'pip', 'install', '--target', str(target), '--ignore-installed', '--no-cache-dir', '--no-compile', '-r', str(requirements)], check=True, timeout=480)
(target / 'cloud_inference.py').write_bytes(s3.get_object(Bucket=artifacts, Key=os.environ['ECOGUARD_HANDLER_KEY'])['Body'].read())
raw = s3.get_object(Bucket=artifacts, Key=source_manifest['ffmpegArchiveKey'])['Body'].read()
if hashlib.sha256(raw).hexdigest() != source_manifest['ffmpegArchiveSha256']: raise RuntimeError('Native archive integrity mismatch')
(target / 'bin').mkdir(exist_ok=True)
with tarfile.open(fileobj=io.BytesIO(raw)) as archive: archive.extractall(target / 'bin', filter='data')
for name in ['ffmpeg', 'ffprobe']: (target / 'bin' / name).chmod(0o755)
# Do not ship third-party test suites or generated bytecode; retain code, runtime data and licences.
import shutil
for path in sorted(target.rglob('*'), key=lambda p: len(p.parts), reverse=True):
    if path.is_dir() and path.name in ['tests', '__pycache__']: shutil.rmtree(path)
size = sum(p.stat().st_size for p in target.rglob('*') if p.is_file())
print('Inference runtime extracted MiB:', size / 1024 / 1024, flush=True)
if size > 240 * 1024 * 1024: raise RuntimeError('Inference package exceeds conservative 240 MiB Lambda ZIP limit')
versions = {d.metadata['Name']: d.version for d in importlib.metadata.distributions(path=[str(target)])}
# Match the deployment environment and prove imports/model loading on the actual Linux CPU build.
env = {**os.environ, 'PYTHONPATH': str(target), 'ECOGUARD_MEDIA_BUCKET': media, 'ECOGUARD_MODEL_BUCKET': media,
 'ECOGUARD_MODEL_KEY': source_manifest['modelKey'], 'ECOGUARD_MODEL_VERSION': source_manifest['modelVersion'],
 'ECOGUARD_MODEL_SHA256': source_manifest['modelSha256'], 'ECOGUARD_MODEL_IDENTITY': source_manifest['identity'],
 'ECOGUARD_MODEL_EXPORTER_VERSION': source_manifest['exporterVersion'], 'ECOGUARD_CONFIDENCE': '0.25'}
archive_path = Path('/tmp/ecoguard-inference.zip')
with zipfile.ZipFile(archive_path, 'w', zipfile.ZIP_DEFLATED) as archive:
    for path in sorted(target.rglob('*')):
        if path.is_file(): archive.write(path, path.relative_to(target))
sha = hashlib.sha256(archive_path.read_bytes()).hexdigest()
key = 'inference/' + sha + '.zip'
s3.upload_file(str(archive_path), artifacts, key)
manifest = {**source_manifest, 'inferenceArtifactKey': key, 'inferenceArchiveSha256': sha, 'inferenceExtractedBytes': size,
 'runtimeDependencies': versions, 'inferenceBuildId': build_id, 'inferencePackageComplete': True}
s3.put_object(Bucket=artifacts, Key='builds/' + build_id + '/inference-manifest.json', Body=json.dumps(manifest).encode(), ContentType='application/json')
subprocess.run([sys.executable, '-c', 'import cloud_inference; session, labels=cloud_inference.model(); print("Linux ONNX import/model preflight:", session.get_inputs()[0].shape, len(labels))'], env=env, check=True, timeout=120)
manifest['nativeImportPreflight'] = True
s3.put_object(Bucket=artifacts, Key='builds/' + build_id + '/inference-manifest.json', Body=json.dumps(manifest).encode(), ContentType='application/json')
print('LINUX INFERENCE PACKAGE COMPLETE', flush=True)
# Controlled, public-source fixtures for real CPU inference/video preflight. No media indexing is involved.
import urllib.request
fixture_dir = Path('/tmp/ecoguard-fixtures'); fixture_dir.mkdir()
with urllib.request.urlopen('https://raw.githubusercontent.com/pytorch/hub/master/images/dog.jpg', timeout=40) as response:
    (fixture_dir / 'dog.jpg').write_bytes(response.read())
tools = Path('/tmp/ecoguard-video-tools')
subprocess.run([sys.executable, '-m', 'pip', 'install', '--target', str(tools), '--ignore-installed', '--no-cache-dir', '--no-compile', 'av==19.0.2'], check=True, timeout=180)
preflight = r'''
import av, boto3, hashlib, io, json, os
from pathlib import Path
from fractions import Fraction
from PIL import Image, ImageOps
import cloud_inference
root = Path('/tmp/ecoguard-fixtures')
raw = (root / 'dog.jpg').read_bytes()
picture = ImageOps.pad(Image.open(io.BytesIO(raw)).convert('RGB'), (640, 480), color=(114,114,114))
video = root / 'dog-11s.mp4'
with av.open(str(video), 'w', format='mp4', options={'movflags': '+faststart'}) as output:
    stream = output.add_stream('libx264', rate=1)
    stream.width, stream.height, stream.pix_fmt = 640, 480, 'yuv420p'
    stream.options = {'preset': 'ultrafast', 'crf': '25'}
    for i in range(11):
        frame = av.VideoFrame.from_image(picture); frame.pts = i; frame.time_base = Fraction(1,1)
        for packet in stream.encode(frame): output.mux(packet)
    for packet in stream.encode(): output.mux(packet)
s3 = boto3.client('s3')
context = type('BuildContext', (), {'get_remaining_time_in_millis': lambda self: 600000})()
fixtures = {}
for mode, path, mime in [('image', root/'dog.jpg', 'image/jpeg'), ('video', video, 'video/mp4')]:
    raw = path.read_bytes(); key = 'verification/' + os.environ['ECOGUARD_BUILD_ID'] + '/' + path.name
    result = s3.put_object(Bucket=os.environ['ECOGUARD_MEDIA_BUCKET'], Key=key, Body=raw, ContentType=mime)
    event = {'mode': mode, 'key': key, 'version': result['VersionId'], 'size': len(raw), 'checksum': hashlib.sha256(raw).hexdigest(), 'contentType': mime}
    detection = cloud_inference.handler(event, context)
    print('Actual Linux preflight', mode, json.dumps(detection), flush=True)
    if detection.get('species', {}).get('dog') != 1: raise RuntimeError('Expected one real detected dog in controlled fixture')
    if mode == 'video' and detection.get('sampledAt') != [0,10]: raise RuntimeError('Incorrect real video sample times')
    fixtures[mode] = {'event': event, 'observed': detection, 'source': 'https://raw.githubusercontent.com/pytorch/hub/master/images/dog.jpg'}
(root/'fixtures.json').write_text(json.dumps(fixtures))
'''
subprocess.run([sys.executable, '-c', preflight], env={**env, 'PYTHONPATH': str(target) + ':' + str(tools)}, check=True, timeout=180)
manifest['linuxPreflightFixtures'] = json.loads((fixture_dir / 'fixtures.json').read_text())
s3.put_object(Bucket=artifacts, Key='builds/' + build_id + '/inference-manifest.json', Body=json.dumps(manifest).encode(), ContentType='application/json')
print('REAL LINUX IMAGE AND VIDEO PREFLIGHT COMPLETE; verify again inside deployed Lambda.', flush=True)
